// Main-test storage starts empty and receives the final schema. This is the
// fresh-database lane; individual tests then exercise the schema.
//
// This setup file runs before every worker test file, against a fresh
// database each time. Replaying all 34 migrations cost ~2.5s per file, so
// the setup instead executes `test/schema-dump.sql` — the final schema the
// migration chain produces, one statement per line for D1 `exec()` — plus
// the same `d1_migrations` bookkeeping the chain would have written. The
// dump is generated by `scripts/generate-test-schema-dump.ts`, and
// `src/db/migrations-upgrade.test.ts` proves once per run that it matches
// the real chain (applied to SCHEMA_REFERENCE_DB) and that populated
// pre-0009 databases upgrade through it without loss.
await env.DB.exec(
  [
    "CREATE TABLE IF NOT EXISTS d1_migrations (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT UNIQUE, applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL)",
    env.TEST_SCHEMA_DUMP,
    ...env.TEST_MIGRATIONS.map(
      (migration) => `INSERT INTO d1_migrations (name) VALUES ('${migration.name}')`,
    ),
  ].join("\n"),
);
await assertBirthCalcSchema(env.DB, "clean apply");
await assertAccountProcessingConsentSchema(env.DB, "clean apply");
await assertReadingSavesSchema(env.DB, "clean apply");
await assertDatabaseHealthy(env.DB, "0031 clean apply");
